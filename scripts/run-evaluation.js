/**
 * scripts/run-evaluation.js
 *
 * Runs the three evaluation suites end-to-end and aggregates the JSON
 * results into:
 *   - zTESE/evaluation_results/SUMMARY.md     (human-readable)
 *   - zTESE/evaluation_results/tables.tex     (LaTeX-ready tables for the paper)
 *
 * Usage:
 *   node scripts/run-evaluation.js              # local hardhat (default)
 *   node scripts/run-evaluation.js --besu       # against a running Besu network
 */

const { spawnSync } = require("child_process");
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const RESULTS_DIR = path.join(ROOT, "zTESE", "evaluation_results");
const useBesu = process.argv.includes("--besu");
const networkArgs = useBesu ? ["--network", "besu"] : [];

function run(label, args) {
  console.log("\n=== " + label + " ===");
  const result = spawnSync("npx", ["hardhat", "test", ...args, ...networkArgs], {
    cwd: ROOT,
    stdio: "inherit",
    shell: true,
  });
  if (result.status !== 0) {
    console.error(label + " failed (exit " + result.status + ")");
    process.exitCode = result.status || 1;
  }
}

if (!fs.existsSync(RESULTS_DIR)) fs.mkdirSync(RESULTS_DIR, { recursive: true });

run("Functional + E2E (§5.1)", ["test/evaluation/Evaluation.functional.test.js"]);
run("Gas per operation (§5.2 - Table I)", ["test/evaluation/Evaluation.gas.test.js"]);
run("AMM slippage curve (§5.2)", ["test/evaluation/Evaluation.slippage.test.js"]);
run("Wall-clock latency per op (§5.2)", ["test/evaluation/Evaluation.latency.test.js"]);
if (!useBesu) {
  run("OrderBook depth scaling (§5.2 - Figure 3)", ["test/evaluation/Evaluation.scaling.test.js"]);
} else {
  console.log("\n[skipping scaling test on besu - requires ad-hoc account funding]");
}

// ---------- Aggregate ----------

function readJson(name) {
  const p = path.join(RESULTS_DIR, name);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, "utf8"));
}

const functional = readJson("functional-results.json");
const gas = readJson("gas-results.json");
const scaling = readJson("scaling-results.json");
const slippage = readJson("slippage-results.json");
const latency = readJson("latency-results.json");

const fmt = (n) => (n == null ? "n/a" : n.toLocaleString("en-US"));

// ---------- SUMMARY.md ----------
let md = "# TSS Evaluation Results\n\n";
md += "_Generated " + new Date().toISOString() + "_\n\n";

if (functional) {
  md += "## §5.1 Functional Validation\n\n";
  md += "Total: " + functional.total + "  |  Passed: " + functional.passed + "\n\n";
  md += "| ID | Description | Result |\n|---|---|---|\n";
  for (const o of functional.outcomes) {
    md += "| " + o.id + " | " + o.description + " | " + (o.passed ? "PASS" : "FAIL") + " |\n";
  }
  md += "\n";
}

if (gas) {
  md += "## §5.2 Gas Cost per Operation (Table I)\n\n";
  md += "| Operation | Gas |\n|---|---:|\n";
  for (const [k, v] of Object.entries(gas.gas)) {
    md += "| " + k + " | " + fmt(v) + " |\n";
  }
  md += "\n";
}

if (scaling) {
  md += "## §5.2 OrderBook Depth Scaling (Figure 3)\n\n";
  md += "| Open orders depth | OrderBook submitOrder gas | AMM swap gas |\n|---:|---:|---:|\n";
  for (const s of scaling.samples) {
    md += "| " + s.depth + " | " + fmt(s.orderBookSubmitGas) + " | " + fmt(s.ammSwapGas) + " |\n";
  }
  md += "\n";
}

if (slippage) {
  md += "## §5.2 AMM Slippage Curve\n\n";
  const reserveEth = (BigInt(slippage.poolReserveCash) / 10n ** 18n).toString();
  md += "Pool reserves: " + reserveEth + " cash / " + reserveEth + " sec, fee " + slippage.feeBps + " bps.\n\n";
  md += "| Trade size (% of pool) | Realised price (cash/sec) | Slippage (%) |\n|---:|---:|---:|\n";
  for (const s of slippage.samples) {
    md += "| " + s.sizePctOfPool + " | " + s.realisedPrice.toFixed(6) + " | " + s.slippagePct + " |\n";
  }
  md += "\n";
}

if (latency) {
  md += "## §5.2 Wall-clock Latency per Operation\n\n";
  md += "Network: `" + latency.network + "`, samples per op: " + latency.samplesPerOp + ".  \n";
  md += "_" + latency.note + "_\n\n";
  md += "| Operation | Mean (ms) | p50 (ms) | p95 (ms) | Min | Max |\n|---|---:|---:|---:|---:|---:|\n";
  for (const [k, v] of Object.entries(latency.results)) {
    md += "| " + k + " | " + v.meanMs + " | " + v.p50Ms + " | " + v.p95Ms + " | " + v.minMs + " | " + v.maxMs + " |\n";
  }
  md += "\n";
}

fs.writeFileSync(path.join(RESULTS_DIR, "SUMMARY.md"), md);
console.log("\nWrote " + path.join(RESULTS_DIR, "SUMMARY.md"));

// ---------- tables.tex ----------
let tex = "% Auto-generated by scripts/run-evaluation.js - do not edit by hand\n";
tex += "% Generated " + new Date().toISOString() + "\n\n";

if (gas) {
  tex += "% Table I: Gas cost per operation\n";
  tex += "\\begin{table}[t]\n\\centering\n\\caption{Gas cost per operation on the TSS prototype}\n";
  tex += "\\label{tab:gas}\n\\begin{tabular}{lr}\n\\hline\nOperation & Gas \\\\\n\\hline\n";
  for (const [k, v] of Object.entries(gas.gas)) {
    tex += k.replace(/_/g, "\\_") + " & " + fmt(v) + " \\\\\n";
  }
  tex += "\\hline\n\\end{tabular}\n\\end{table}\n\n";
}

if (scaling) {
  tex += "% Figure 3 data: OrderBook depth scaling\n";
  tex += "\\begin{table}[t]\n\\centering\n\\caption{OrderBook submitOrder gas as a function of open-order depth, vs. AMM constant swap cost}\n";
  tex += "\\label{tab:scaling}\n\\begin{tabular}{rrr}\n\\hline\nDepth & OB submitOrder & AMM swap \\\\\n\\hline\n";
  for (const s of scaling.samples) {
    tex += s.depth + " & " + fmt(s.orderBookSubmitGas) + " & " + fmt(s.ammSwapGas) + " \\\\\n";
  }
  tex += "\\hline\n\\end{tabular}\n\\end{table}\n\n";
}

if (slippage) {
  const reserveEth = (BigInt(slippage.poolReserveCash) / 10n ** 18n).toString();
  tex += "% AMM slippage curve (§5.2)\n";
  tex += "\\begin{table}[t]\n\\centering\n\\caption{AMM realised slippage as a function of trade size (pool reserves "
       + reserveEth + " cash / " + reserveEth + " sec, fee "
       + slippage.feeBps + " bps)}\n";
  tex += "\\label{tab:slippage}\n\\begin{tabular}{rrr}\n\\hline\nSize (\\% of pool) & Realised price & Slippage (\\%) \\\\\n\\hline\n";
  for (const s of slippage.samples) {
    tex += s.sizePctOfPool + " & " + s.realisedPrice.toFixed(6) + " & " + s.slippagePct + " \\\\\n";
  }
  tex += "\\hline\n\\end{tabular}\n\\end{table}\n\n";
}

if (latency) {
  tex += "% Wall-clock latency (§5.2)\n";
  tex += "\\begin{table}[t]\n\\centering\n\\caption{Per-operation wall-clock latency on " + latency.network + " (" + latency.samplesPerOp + " samples per op)}\n";
  tex += "\\label{tab:latency}\n\\begin{tabular}{lrrrrr}\n\\hline\nOperation & Mean (ms) & p50 & p95 & Min & Max \\\\\n\\hline\n";
  for (const [k, v] of Object.entries(latency.results)) {
    tex += k.replace(/_/g, "\\_") + " & " + v.meanMs + " & " + v.p50Ms + " & " + v.p95Ms + " & " + v.minMs + " & " + v.maxMs + " \\\\\n";
  }
  tex += "\\hline\n\\end{tabular}\n\\end{table}\n\n";
}

if (functional) {
  tex += "% Functional outcomes (§5.1)\n";
  tex += "\\begin{table}[t]\n\\centering\n\\caption{Functional and negative-test outcomes}\n";
  tex += "\\label{tab:functional}\n\\begin{tabular}{llc}\n\\hline\nID & Scenario & Result \\\\\n\\hline\n";
  for (const o of functional.outcomes) {
    tex += o.id + " & " + o.description.replace(/&/g, "\\&") + " & " + (o.passed ? "PASS" : "FAIL") + " \\\\\n";
  }
  tex += "\\hline\n\\end{tabular}\n\\end{table}\n";
}

fs.writeFileSync(path.join(RESULTS_DIR, "tables.tex"), tex);
console.log("Wrote " + path.join(RESULTS_DIR, "tables.tex"));
console.log("\nDone.");
